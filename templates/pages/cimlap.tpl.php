<h3>Mit jelent az EDC?</h3>

<p>
    Az EDC az angol „every day carry” kifejezés rövidítése.
    Azokat az eszközöket jelenti, amelyeket a mindennapokban
    magunkkal hordunk. Ilyen lehet egy zseblámpa, egy
    multiszerszám vagy egy jegyzetfüzet.
</p>

<h3>Felszerelések és tapasztalatok</h3>

<p>
    Egy eszköz kiválasztásánál fontos, hogy mire szeretnénk használni.
    Más felszerelésre lehet szükségünk munka közben, kiránduláson
    vagy a hétköznapi teendők során.
    A bemutatók segítenek megismerni az eszközök tulajdonságait.
</p>

